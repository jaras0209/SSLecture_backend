-- 初始結構：對應前端 docs/database_schema.md 第 6 節（v1.8.0），共 22 張表。
-- 為了同時能在 H2 與 PostgreSQL 執行，與文件原始 SQL 的差異如下（設計意圖不變）：
--   * PostgreSQL ENUM 型別       → VARCHAR + CHECK (... IN (...))，JPA 以 @Enumerated(STRING) 對應
--   * gen_random_uuid()          → ${uuid_fn}（依資料庫替換）
--   * NOW()                      → CURRENT_TIMESTAMP
--   * TIMESTAMPTZ                → TIMESTAMP WITH TIME ZONE（同一型別的標準寫法）
--   * users.email 的 lower() 部分唯一索引 → 一律小寫儲存（CHECK）+ 一般 UNIQUE（NULL 可重複）
--   * avatar_url ~ '^https://'   → LIKE 'https://%'
--   * username 的正規表示式 CHECK → 移到 002（兩種資料庫語法不同）
--   * btrim()                    → TRIM()
--   * BIGSERIAL                  → BIGINT GENERATED BY DEFAULT AS IDENTITY
--   * INET                       → VARCHAR(45)（IPv6 最長 45 字元）
--   * TEXT[]                     → ${text_array}
-- ═════════════════════════════════════════════════════════════════════════════

--changeset sslecture:001-churches
CREATE TABLE churches (
  id         UUID                     DEFAULT ${uuid_fn} PRIMARY KEY,
  name       VARCHAR(100)             NOT NULL UNIQUE,
  region     VARCHAR(100),
  is_active  BOOLEAN                  NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
--rollback DROP TABLE churches;

--changeset sslecture:001-users
CREATE TABLE users (
  id                   UUID                     DEFAULT ${uuid_fn} PRIMARY KEY,
  username             VARCHAR(30)              NOT NULL UNIQUE,
  password_hash        VARCHAR(255),            -- NULL = 只用社群登入
  role                 VARCHAR(20)              NOT NULL
                       CONSTRAINT ck_users_role CHECK (role IN ('student', 'teacher', 'pastor', 'parent', 'admin')),
  church_id            UUID                     REFERENCES churches(id) ON DELETE SET NULL,
  display_name         VARCHAR(100),
  real_name            VARCHAR(100),
  gender               VARCHAR(10)              -- 只用於 student / teacher；NULL = 未設定
                       CONSTRAINT ck_users_gender CHECK (gender IN ('male', 'female')),
  email                VARCHAR(255)             -- 選填，小寫儲存
                       CONSTRAINT ck_users_email_lower CHECK (email = LOWER(email)),
  email_verified       BOOLEAN                  NOT NULL DEFAULT FALSE,
  must_change_password BOOLEAN                  NOT NULL DEFAULT FALSE,
  avatar_url           VARCHAR(2048)            -- 只接受 https（見 2.1）
                       CONSTRAINT ck_users_avatar_https CHECK (avatar_url LIKE 'https://%'),
  login_method         VARCHAR(20)              NOT NULL DEFAULT 'credentials'
                       CONSTRAINT ck_users_login_method CHECK (login_method IN ('credentials', 'google', 'line')),
  token_version        INTEGER                  NOT NULL DEFAULT 0,   -- 遞增即讓既有登入失效（見 5.15）
  is_active            BOOLEAN                  NOT NULL DEFAULT TRUE,
  last_login_at        TIMESTAMP WITH TIME ZONE,
  created_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_users_email UNIQUE (email)
);
CREATE INDEX idx_users_church_role ON users(church_id, role);
--rollback DROP TABLE users;

